function test_module2_batch_dataset_contract_2d(dataset, options)
% TEST_MODULE2_BATCH_DATASET_CONTRACT_2D Verify the v2 field-pair contract.
setup_project_paths;
if nargin < 2 || isempty(options)
    options = default_module2_batch_fem_options_2d();
end
if nargin < 1 || isempty(dataset)
    dataset = generate_module2_batch_fem_dataset_2d(options);
end

report = validate_module2_batch_fem_dataset_2d( ...
    dataset, options.validation, true);
assert(report.passed, 'Batch dataset validation report did not pass.');
assert(strcmp(dataset.schema, 'module2_field_to_field_fem_dataset_v2'), ...
    'Unexpected Module 2 field-to-field dataset schema.');
assert(strcmp(dataset.inputRepresentation, 'nodal_total_charge_density'), ...
    'Canonical input must be the nodal total charge-density field.');
assert(strcmp(dataset.outputRepresentation, 'nodal_electrostatic_potential'), ...
    'Canonical output must be the nodal electrostatic-potential field.');
assert(strcmp(dataset.coordinateNames{2}, 'z'), ...
    'The Module 9 dataset second coordinate must be named z.');
assert(isfield(dataset, 'syntheticGenerator'), ...
    'Default pilot must record its synthetic field-generator provenance.');
assert(strcmp(dataset.syntheticGenerator.parameterNames{3}, 'z_c'), ...
    'Gaussian generator metadata must use z_c for the second coordinate.');
assert(strcmp(dataset.syntheticGenerator.role, ...
    'training_field_generation_only_not_surrogate_input'), ...
    'Gaussian parameters were not clearly demoted to generator metadata.');
assert(strcmp(dataset.boundaryConditions.jjTreatment, ...
    'scoring_interface_only'), ...
    'JJ-sensitive region was not preserved as a scoring interface.');

fprintf(['test_module2_batch_dataset_contract_2d passed: ', ...
    '%d/%d checks.\n'], report.nPassed, report.nChecks);
end
