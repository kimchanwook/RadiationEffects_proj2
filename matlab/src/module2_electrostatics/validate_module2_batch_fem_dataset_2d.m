function report = validate_module2_batch_fem_dataset_2d( ...
    dataset, tolerances, throwOnFailure)
% VALIDATE_MODULE2_BATCH_FEM_DATASET_2D Audit the v2 field-to-field dataset.

if nargin < 2 || isempty(tolerances)
    defaults = default_module2_batch_fem_options_2d();
    tolerances = defaults.validation;
end
if nargin < 3
    throwOnFailure = false;
end

checks = struct('name', {}, 'passed', {}, 'message', {});
requiredFields = {'schema', 'inputRepresentation', 'inputUnits', ...
    'outputRepresentation', 'outputUnits', 'mesh', 'caseNames', 'nCases', ...
    'rho', 'phi', 'diagnostics', 'trainCases', 'validationCases', ...
    'testCases', 'fixedNodes', 'fixedValues', 'provenance'};
for k = 1:numel(requiredFields)
    present = isfield(dataset, requiredFields{k});
    checks(end + 1) = make_check( ...
        ['field_', requiredFields{k}], present, ...
        ['required dataset field ', requiredFields{k}]); %#ok<AGROW>
end
if any(~[checks.passed])
    report = finalize_report(checks, NaN, NaN, NaN);
    if throwOnFailure
        throw_failure(report);
    end
    return;
end

nNodes = size(dataset.mesh.nodes, 1);
nCases = dataset.nCases;
checks(end + 1) = make_check('schema_v2', ...
    strcmp(dataset.schema, 'module2_field_to_field_fem_dataset_v2'), ...
    'dataset must use module2_field_to_field_fem_dataset_v2');
checks(end + 1) = make_check('field_input_contract', ...
    strcmp(dataset.inputRepresentation, 'nodal_total_charge_density') && ...
    strcmp(dataset.inputUnits, 'C/m^3'), ...
    'input must be nodal total charge density in C/m^3');
checks(end + 1) = make_check('field_output_contract', ...
    strcmp(dataset.outputRepresentation, 'nodal_electrostatic_potential') && ...
    strcmp(dataset.outputUnits, 'V'), ...
    'output must be nodal electrostatic potential in volts');
checks(end + 1) = make_check('phi_shape', ...
    isequal(size(dataset.phi), [nNodes, nCases]), ...
    'phi must be nNodes-by-nCases');
checks(end + 1) = make_check('rho_shape', ...
    isequal(size(dataset.rho), [nNodes, nCases]), ...
    'rho must be nNodes-by-nCases and is mandatory in the v2 contract');
checks(end + 1) = make_check('case_name_count', ...
    numel(dataset.caseNames) == nCases, ...
    'caseNames must contain one name per complete field configuration');
checks(end + 1) = make_check('diagnostic_count', ...
    numel(dataset.diagnostics) == nCases, ...
    'diagnostics must contain one entry per field configuration');
checks(end + 1) = make_check('finite_rho', ...
    all(isfinite(dataset.rho(:))), ...
    'all charge-field values must be finite');
checks(end + 1) = make_check('finite_phi', ...
    all(isfinite(dataset.phi(:))), ...
    'all potential-field values must be finite');
checks(end + 1) = make_check('zero_field_control_present', ...
    any(all(dataset.rho == 0, 1)), ...
    'at least one exact zero-charge field control is required in the pilot');

allSplitCases = [dataset.trainCases(:); dataset.validationCases(:); ...
    dataset.testCases(:)];
indicesValid = all(isfinite(allSplitCases)) && ...
    all(allSplitCases == round(allSplitCases)) && ...
    all(allSplitCases >= 1) && all(allSplitCases <= nCases);
checks(end + 1) = make_check('split_indices_valid', indicesValid, ...
    'split indices must be integer complete-case indices inside the dataset');
checks(end + 1) = make_check('splits_disjoint', ...
    numel(unique(allSplitCases)) == numel(allSplitCases), ...
    'train, validation, and test field configurations must be disjoint');
if tolerances.requireCompleteSplits
    complete = isequal(sort(allSplitCases(:)), (1:nCases).');
else
    complete = true;
end
checks(end + 1) = make_check('splits_complete', complete, ...
    'split indices must cover every complete field configuration once');

fixedPhi = dataset.phi(dataset.fixedNodes, :);
expectedFixed = repmat(dataset.fixedValues(:), 1, nCases);
directBoundaryError = max(abs(fixedPhi(:) - expectedFixed(:)));
checks(end + 1) = make_check('dirichlet_values', ...
    directBoundaryError <= tolerances.dirichletErrorInf, ...
    sprintf('maximum direct Dirichlet error %.3e', directBoundaryError));

freeResiduals = [dataset.diagnostics.freeResidualRelative];
balances = [dataset.diagnostics.globalBalanceRelative];
diagnosticBcErrors = [dataset.diagnostics.dirichletErrorInf];
maxFreeResidual = max(freeResiduals);
maxBalance = max(balances);
maxDiagnosticBcError = max(diagnosticBcErrors);
checks(end + 1) = make_check('free_residuals', ...
    maxFreeResidual <= tolerances.freeResidualRelative, ...
    sprintf('maximum relative free-node residual %.3e', maxFreeResidual));
checks(end + 1) = make_check('global_balance', ...
    maxBalance <= tolerances.globalBalanceRelative, ...
    sprintf('maximum relative source/reaction imbalance %.3e', maxBalance));
checks(end + 1) = make_check('diagnostic_dirichlet_error', ...
    maxDiagnosticBcError <= tolerances.dirichletErrorInf, ...
    sprintf('maximum diagnostic Dirichlet error %.3e', maxDiagnosticBcError));

if isfield(dataset, 'tags') && isfield(dataset.tags, 'top') && ...
        isfield(dataset.tags.top, 'jj_sensitive') && ...
        isfield(dataset.tags, 'electrode')
    jjEdges = dataset.tags.top.jj_sensitive.edgeIds(:);
    electrodeEdges = unique([ ...
        dataset.tags.electrode.left_electrode.edgeIds(:); ...
        dataset.tags.electrode.right_electrode.edgeIds(:)]);
    jjPass = isempty(intersect(jjEdges, electrodeEdges));
else
    jjPass = true;
end
checks(end + 1) = make_check('jj_edge_not_dirichlet', jjPass, ...
    'the JJ edge must remain a scoring interface, not a voltage boundary');
checks(end + 1) = make_check('single_operator_reuse', ...
    dataset.provenance.stiffnessAssemblyCount == 1 && ...
    dataset.provenance.factorizationCount == 1 && ...
    dataset.provenance.linearSolveCount == nCases && ...
    dataset.provenance.meshReusedForEveryCase, ...
    'one stiffness assembly and one factorization must serve all fields');
checks(end + 1) = make_check('batch_plot_default', ...
    ~dataset.provenance.numericalGeneratorCreatesPlots, ...
    'numerical batch generation must not create routine plots');

report = finalize_report( ...
    checks, maxFreeResidual, maxBalance, directBoundaryError);
if throwOnFailure && ~report.passed
    throw_failure(report);
end
end

function check = make_check(name, passed, message)
check.name = name;
check.passed = logical(passed);
check.message = message;
end

function report = finalize_report(checks, maxResidual, maxBalance, maxBcError)
report.schema = 'module2_batch_fem_validation_v2';
report.checks = checks;
report.nChecks = numel(checks);
report.nPassed = sum([checks.passed]);
report.passed = report.nPassed == report.nChecks;
report.maxFreeResidualRelative = maxResidual;
report.maxGlobalBalanceRelative = maxBalance;
report.maxDirichletErrorInf = maxBcError;
end

function throw_failure(report)
failed = report.checks(~[report.checks.passed]);
messages = cell(numel(failed), 1);
for k = 1:numel(failed)
    messages{k} = [failed(k).name, ': ', failed(k).message];
end
error('Module2BatchFEM:ValidationFailed', ...
    'Batch FEM dataset validation failed:\n%s', strjoin(messages, '\n'));
end
