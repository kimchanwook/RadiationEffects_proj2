function design = make_module2_batch_parameter_design_2d()
% MAKE_MODULE2_BATCH_PARAMETER_DESIGN_2D Deterministic 17-case pilot design.
%
%   The five conditional parameters are
%
%       mu = [C_peak, x_c, z_c, sigma_x, sigma_z].
%
%   The design covers a zero control plus changes in amplitude, depth,
%   lateral position, and anisotropic width. Split indices refer to complete
%   charge configurations, preventing node-level leakage between training,
%   validation, and test sets.

design.schema = 'module2_gaussian_parameter_design_v1';
design.parameterNames = {'C_peak', 'x_c', 'z_c', 'sigma_x', 'sigma_z'};
design.parameterUnits = {'m^-3', 'm', 'm', 'm', 'm'};

design.caseNames = { ...
    'zero_control'; ...
    'center_shallow_low'; ...
    'center_shallow_high'; ...
    'center_mid_narrow'; ...
    'center_mid_broad'; ...
    'center_deep_low'; ...
    'center_deep_high'; ...
    'left_near_jj'; ...
    'right_near_jj'; ...
    'left_pad_shallow'; ...
    'right_pad_shallow'; ...
    'far_left_mid'; ...
    'far_right_mid'; ...
    'left_deep_broad'; ...
    'right_deep_broad'; ...
    'asymmetric_wide_left'; ...
    'asymmetric_tall_right'};

% Columns: C_peak [m^-3], x_c [m], z_c [m], sigma_x [m], sigma_z [m].
design.parameters = [ ...
    0.0,    0.0,       -250e-6,  50e-6,  25e-6; ...
    5e15,   0.0,        -20e-6,  25e-6,  10e-6; ...
    2e16,   0.0,        -20e-6,  25e-6,  10e-6; ...
    1e16,   0.0,       -150e-6,  20e-6,  20e-6; ...
    1e16,   0.0,       -150e-6, 150e-6,  75e-6; ...
    5e15,   0.0,       -400e-6,  50e-6,  30e-6; ...
    2e16,   0.0,       -400e-6,  50e-6,  30e-6; ...
    1e16, -100e-6,      -35e-6,  30e-6,  15e-6; ...
    1e16,  100e-6,      -35e-6,  30e-6,  15e-6; ...
    1e16, -450e-6,      -30e-6,  80e-6,  20e-6; ...
    1e16,  450e-6,      -30e-6,  80e-6,  20e-6; ...
    1e16,   -1.0e-3,   -250e-6, 120e-6,  60e-6; ...
    1e16,    1.0e-3,   -250e-6, 120e-6,  60e-6; ...
    1e16, -500e-6,     -375e-6, 200e-6,  80e-6; ...
    1e16,  500e-6,     -375e-6, 200e-6,  80e-6; ...
    2e16, -300e-6,     -100e-6, 300e-6,  30e-6; ...
    2e16,  300e-6,     -200e-6,  50e-6, 120e-6];

% Eleven training cases and three cases in each held-out subset. Mirror
% partners are intentionally separated in several places to test lateral
% generalization without leaking nodes from a held-out configuration.
design.trainCases = [1, 2, 3, 4, 5, 6, 7, 8, 9, 12, 13];
design.validationCases = [10, 14, 16];
design.testCases = [11, 15, 17];
end
